#!/usr/bin/env python3
"""autostub.py OBJ... > autostub.c

Emit weak definitions for every symbol the objects reference but none of
them defines, so a large ircd module (history.c, metadata.c,
bouncer_session.c, ...) links standalone with only the handful of stubs a
harness writes by hand.  A symbol called through the PLT is a function and
gets a weak 'return 0' body; anything else is data and gets weak zeroed
storage.  libc/libstdc++/sanitizer/library symbols are left to the linker.
"""
import re
import subprocess
import sys

objs = sys.argv[1:]
skip_libs = sys.argv[sys.argv.index('--libs') + 1:] if '--libs' in sys.argv else []
if '--libs' in sys.argv:
    objs = sys.argv[1:sys.argv.index('--libs')]

defined, undefined = set(), set()
for o in objs:
    out = subprocess.run(['nm', o], capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])
        elif len(parts) == 3 and parts[1] not in ('U', 'w', 'v'):
            defined.add(parts[2])

# symbols the system libraries provide
libsyms = set()
libs = ['/lib/x86_64-linux-gnu/libc.so.6', '/lib/x86_64-linux-gnu/libm.so.6']
for name in ['libssl.so', 'libcrypto.so', 'libjansson.so', 'libzstd.so',
             'libcurl.so', 'librocksdb.so', 'libcmocka.so', 'libmaxminddb.so',
             'libGeoIP.so', 'libgit2.so'] + skip_libs:
    libs.append('/usr/lib/x86_64-linux-gnu/' + name)
for lib in libs:
    out = subprocess.run(['nm', '-D', '--defined-only', lib],
                         capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if parts:
            libsyms.add(parts[-1].split('@')[0])

funcs = set()
for o in objs:
    out = subprocess.run(['objdump', '-r', o], capture_output=True, text=True).stdout
    for line in out.splitlines():
        m = re.search(r'R_X86_64_PLT32\s+(\S+?)(?:-0x[0-9a-f]+)?$', line)
        if m:
            funcs.add(m.group(1))

need = sorted(s for s in undefined - defined - libsyms
              if not s.startswith(('__asan', '__ubsan', '__sanitizer', '__sancov',
                                   '__start_', '__stop_', '_GLOBAL_OFFSET', '__dso',
                                   '__lsan', '__msan', '__libc', '_ITM', '__cxa',
                                   '__gmon', '__TMC', 'LLVMFuzzer', '__llvm')))
print('/* generated by common/autostub.py: weak fallbacks for symbols the')
print(' * linked ircd objects reference but the fuzz build does not provide */')
for s in need:
    if s in funcs:
        print('__attribute__((weak)) long %s(void) { return 0; }' % s)
    else:
        print('__attribute__((weak, aligned(64))) char %s[8192];' % s)

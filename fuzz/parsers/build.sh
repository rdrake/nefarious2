#!/bin/bash
# build.sh - build every parser fuzz harness twice:
#   out/fuzz_<t>   libFuzzer + ASan + UBSan (the fuzzing binary)
#   out/repro_<t>  plain ASan + UBSan with common/standalone_main.c (triage)
#
# Needs a configured tree (config.h at the repo root); runs ./configure
# with the CLAUDE.md options when it is missing.  No ircd source is
# modified; harnesses #include or link the real ircd/*.c files.
#
#   ./build.sh            build all targets
#   ./build.sh kc_jwt ... build the named targets only
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
OUT=$HERE/out
mkdir -p "$OUT"
CC=${CC:-clang}

if [ ! -f "$ROOT/config.h" ]; then
  (cd "$ROOT" && ./configure --enable-debug --with-maxcon=4096 \
     --with-rocksdb=/usr --with-zstd=/usr --enable-keycloak >/dev/null)
fi

SAN="-fsanitize=address,undefined -fno-sanitize-recover=undefined -fno-omit-frame-pointer"
CFLAGS_COMMON="-g -O1 -w -I$ROOT/include -I$ROOT -I$ROOT/ircd -I$HERE/sasl_auth -I$HERE/common -DFUZZING_BUILD_MODE_UNSAFE_FOR_PRODUCTION"
I=$ROOT/ircd
C=$HERE/common

# target -> "harness.c [extra sources...] | libs"
declare -A T
# targets whose remaining undefined ircd symbols get weak fallbacks
# generated by common/autostub.py (see that file)
declare -A A
T[websocket]="websocket/fuzz_websocket.c $I/ircd_alloc.c $I/ircd_string.c $C/ircd_stubs.c | -lssl -lcrypto"
T[kc_webhook]="kc_webhook/fuzz_kc_webhook.c $I/kc/kc_webhook_sig.c $I/webhook_subject.c $I/webhook_eventlog.c $I/account_id.c $I/webpush_keyring.c $C/kc_log_stub.c | -ljansson -lcrypto"
T[sasl_auth]="sasl_auth/fuzz_sasl_auth.c sasl_auth/sasl_stubs.c $I/ircd_alloc.c $I/ircd_string.c $I/account_id.c $I/webpush_keyring.c $C/ircd_stubs.c | -lssl -lcrypto -ljansson"
T[ircd_string]="ircd_string/fuzz_ircd_string.c $I/ircd_string.c $I/numnicks.c $I/match.c $I/ircd_alloc.c $C/ircd_stubs.c | -ljansson"
T[match]="match/fuzz_match.c $I/match.c $I/ircd_string.c $C/ircd_stubs.c |"
T[history]="history/fuzz_history.c $C/fake_db.c $I/ml_content.c $I/ircd_compress.c $I/redact_index.c $I/db_casefold.c $I/ircd_string.c $I/ircd_snprintf.c $I/ircd_alloc.c $C/ircd_stubs.c | -lzstd -lcrypto"
A[history]=1
T[kc_base64]="kc_base64/fuzz_kc_base64.c $I/kc/kc_base64.c |"
T[kc_url]="kc_url/fuzz_kc_url.c $I/kc/kc_url.c $C/kc_log_stub.c | -lcurl"
T[kc_error_classify]="kc_error_classify/fuzz_kc_error_classify.c $I/kc/kc_error_classify.c $C/kc_log_stub.c | -ljansson"
T[kc_cache]="kc_cache/fuzz_kc_cache.c $I/kc/kc_cache.c $C/kc_log_stub.c | -ljansson"
T[kc_cred_derive]="kc_cred_derive/fuzz_kc_cred_derive.c $I/kc/kc_cred_derive.c $I/kc/kc_base64.c | -ljansson -lcrypto"
T[chathistory]="chathistory/fuzz_chathistory.c $C/fake_db.c $I/history.c $I/ml_content.c $I/ircd_compress.c $I/redact_index.c $I/db_casefold.c $I/ircd_string.c $I/ircd_snprintf.c $I/ircd_alloc.c $C/ircd_stubs.c | -lzstd -lcrypto -lssl -ljansson"
A[chathistory]=1
T[metadata]="metadata/fuzz_metadata.c metadata/mmeta_wrap.c $C/fake_db.c $I/ircd_compress.c $I/db_casefold.c $I/ircd_string.c $I/ircd_snprintf.c $I/ircd_alloc.c $C/ircd_stubs.c | -lzstd -lcrypto -lssl -ljansson"
A[metadata]=1
T[webpush_line]="webpush_line/fuzz_webpush_line.c $I/webpush_line.c |"
T[webpush_mute]="webpush_mute/fuzz_webpush_mute.c $I/webpush_mute.c |"
T[webpush_expiry]="webpush_expiry/fuzz_webpush_expiry.c $I/webpush_expiry.c |"
T[webpush_keyring]="webpush_keyring/fuzz_webpush_keyring.c $I/webpush_keyring.c |"
T[account_id]="account_id/fuzz_account_id.c $I/account_id.c $I/webpush_keyring.c |"
T[recv_classify]="recv_classify/fuzz_recv_classify.c $I/recv_classify.c |"
T[exit_reason]="exit_reason/fuzz_exit_reason.c $I/exit_reason.c |"
T[register_throttle]="register_throttle/fuzz_register_throttle.c $OUT/gen/register_throttle_small.c |"
T[webhook_eventlog]="webhook_eventlog/fuzz_webhook_eventlog.c $I/webhook_eventlog.c |"
T[webpush]="webpush/fuzz_webpush.c webpush/mwebpush_wrap.c $I/webpush_keyring.c $I/webpush_line.c $I/webpush_mute.c $I/webpush_expiry.c $I/webpush_attention.c $I/ircd_string.c $I/ircd_snprintf.c $I/ircd_alloc.c $C/ircd_stubs.c | -lssl -lcrypto -ljansson -lcurl"
A[webpush]=1
T[bouncer_record]="bouncer_record/fuzz_bouncer_record.c $C/fake_db.c $I/ircd_snprintf.c $I/ircd_string.c $I/ircd_alloc.c $I/account_id.c $I/webpush_keyring.c $C/ircd_stubs.c | -lssl -lcrypto -ljansson -lzstd"
A[bouncer_record]=1
T[kc_jwt]="kc_jwt/fuzz_kc_jwt.c $I/kc/kc_base64.c $C/kc_log_stub.c | -ljansson -lcrypto"

# register_throttle is built like its cmocka suite: 1 bucket x 4 slots
mkdir -p "$OUT/gen"
printf '#define REG_THROTTLE_TABLE_BITS 0\n#define REG_THROTTLE_BUCKET_DEPTH 4\n#include "%s/register_throttle.c"\n' "$I" > "$OUT/gen/register_throttle_small.c"

# per-target extra compiler flags
declare -A F
# F8 (FINDINGS.md): iptobase64() shifts a promoted uint16 into the sign
# bit for every IPv4 address >= 128.0.0.0; left on, UBSan stops the
# campaign at the first such address.  repro_ builds keep the check.
F[ircd_string]="-fno-sanitize=shift-base"

# targets whose remaining undefined ircd symbols get weak fallbacks
# generated by common/autostub.py (see that file)

build_variant() {   # name variant(fuzz|repro) sources...
  local name=$1 var=$2; shift 2
  local od=$OUT/obj/$name/$var objs=() flags
  mkdir -p "$od"
  if [ "$var" = fuzz ]; then flags="$SAN ${F[$name]} -fsanitize=fuzzer-no-link"; else flags="$SAN"; fi
  local i=0
  for s in "$@"; do
    local o=$od/$i.$(basename "${s%.c}").o
    $CC $CFLAGS_COMMON $flags -c "$s" -o "$o"
    objs+=("$o"); i=$((i+1))
  done
  if [ "$var" = repro ]; then
    $CC $CFLAGS_COMMON $flags -c "$C/standalone_main.c" -o "$od/main.o"
    objs+=("$od/main.o")
  fi
  if [ -n "${A[$name]}" ]; then
    python3 "$C/autostub.py" "${objs[@]}" > "$od/autostub.c"
    $CC -g -O0 -w -c "$od/autostub.c" -o "$od/autostub.o"
    objs+=("$od/autostub.o")
  fi
  if [ "$var" = fuzz ]; then
    $CC $SAN -fsanitize=fuzzer "${objs[@]}" -o "$OUT/fuzz_$name" $LIBS
  else
    $CC $SAN "${objs[@]}" -o "$OUT/repro_$name" $LIBS
  fi
}

build_one() {
  local name=$1 spec=${T[$1]}
  local srcs=${spec%%|*} abs=()
  LIBS=${spec#*|}
  for s in $srcs; do case $s in /*) abs+=("$s");; *) abs+=("$HERE/$s");; esac; done
  echo "[build] $name"
  build_variant "$name" fuzz "${abs[@]}"
  build_variant "$name" repro "${abs[@]}"
}

if [ $# -gt 0 ]; then targets="$*"; else targets=$(printf '%s\n' "${!T[@]}" | sort); fi
for t in $targets; do build_one "$t"; done

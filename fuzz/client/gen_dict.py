def esc(w):
    out = []
    for ch in w.encode("utf-8", "surrogatepass"):
        c = chr(ch)
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif 0x20 <= ch < 0x7f:
            out.append(c)
        else:
            out.append("\\x%02x" % ch)
    return "".join(out)

